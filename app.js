const languageButtons = document.querySelectorAll("[data-lang]");
const translatableNodes = document.querySelectorAll("[data-i18n]");
const whatsappLinks = document.querySelectorAll("[data-whatsapp]");
const scenarioButtons = document.querySelectorAll("[data-scenario]");
const menuButton = document.querySelector("#menuButton");
const mobileNav = document.querySelector("#mobileNav");

let currentLanguage = getInitialLanguage();
let currentScenario = "hostel";

function getInitialLanguage() {
  const params = new URLSearchParams(window.location.search);
  const urlLanguage = params.get("lang");
  if (urlLanguage === "es" || urlLanguage === "ru") return urlLanguage;

  try {
    const storedLanguage = localStorage.getItem("ai-gnatev-language");
    if (storedLanguage === "es" || storedLanguage === "ru") {
      return storedLanguage;
    }
  } catch {
    // Local storage may be unavailable for restricted file URLs.
  }

  return "es";
}

function setLanguage(language, updateUrl = true) {
  currentLanguage = language;
  document.documentElement.lang = language;

  translatableNodes.forEach((node) => {
    const key = node.dataset.i18n;
    const value = translations[language][key];
    if (typeof value === "string") node.textContent = value;
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === language;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  const message = encodeURIComponent(translations[language].whatsappMessage);
  whatsappLinks.forEach((link) => {
    link.href = `https://wa.me/59891973677?text=${message}`;
  });

  const description =
    language === "es"
      ? "AI-Gnatev Engineering integra inteligencia artificial en procesos reales de pequeñas empresas en Montevideo: atención, operación y documentos."
      : "AI-Gnatev Engineering внедряет искусственный интеллект в реальные процессы малого бизнеса в Монтевидео: обращения, операции и документы.";
  document.querySelector('meta[name="description"]').content = description;
  document.title =
    language === "es"
      ? "AI-Gnatev Engineering | Integración práctica de IA"
      : "AI-Gnatev Engineering | Практическая интеграция ИИ";

  try {
    localStorage.setItem("ai-gnatev-language", language);
  } catch {
    // The page remains usable without persistence.
  }

  if (updateUrl) {
    const url = new URL(window.location.href);
    if (language === "es") {
      url.searchParams.delete("lang");
    } else {
      url.searchParams.set("lang", language);
    }
    history.replaceState(null, "", url.href);
  }

  renderScenario(currentScenario);
}

function renderScenario(id) {
  currentScenario = id;
  const scenario = scenarios[currentLanguage][id];

  document.querySelector("#demoAvatar").textContent = scenario.avatar;
  document.querySelector("#demoPerson").textContent = scenario.person;
  document.querySelector("#demoMessage").textContent = scenario.message;
  document.querySelector("#demoProcessingText").textContent =
    scenario.processing;
  document.querySelector("#demoProductLabel").textContent =
    scenario.productLabel;
  document.querySelector("#demoTypeLabel").textContent = scenario.typeLabel;
  document.querySelector("#demoResultTitle").textContent =
    scenario.resultTitle;
  document.querySelector("#demoStatus").textContent = scenario.status;
  document.querySelector("#demoAction").textContent = scenario.action;
  document.querySelector("#demoFootnote").textContent = scenario.footnote;

  const fields = document.querySelector("#demoFields");
  fields.replaceChildren();
  scenario.fields.forEach(([label, value]) => {
    const row = document.createElement("div");
    const term = document.createElement("dt");
    const description = document.createElement("dd");
    term.textContent = label;
    description.textContent = value;
    row.append(term, description);
    fields.appendChild(row);
  });

  scenarioButtons.forEach((button) => {
    const active = button.dataset.scenario === id;
    button.classList.toggle("active", active);
    button.setAttribute("aria-selected", String(active));
    button.tabIndex = active ? 0 : -1;
  });
}

function closeMobileMenu() {
  mobileNav.classList.remove("open");
  menuButton.setAttribute("aria-expanded", "false");
  document.body.classList.remove("menu-open");
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

scenarioButtons.forEach((button, index) => {
  button.addEventListener("click", () => renderScenario(button.dataset.scenario));
  button.addEventListener("keydown", (event) => {
    if (!["ArrowLeft", "ArrowRight"].includes(event.key)) return;
    event.preventDefault();
    const direction = event.key === "ArrowRight" ? 1 : -1;
    const nextIndex =
      (index + direction + scenarioButtons.length) % scenarioButtons.length;
    scenarioButtons[nextIndex].focus();
    renderScenario(scenarioButtons[nextIndex].dataset.scenario);
  });
});

menuButton.addEventListener("click", () => {
  const opening = !mobileNav.classList.contains("open");
  mobileNav.classList.toggle("open", opening);
  menuButton.setAttribute("aria-expanded", String(opening));
  document.body.classList.toggle("menu-open", opening);
});

mobileNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMobileMenu);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMobileMenu();
});

document.querySelector("#currentYear").textContent = new Date().getFullYear();
setLanguage(currentLanguage, false);
